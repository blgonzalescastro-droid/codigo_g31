animales = ["perro", "gato", "pájaro"]

"""for" es una estructura de control que permite iterar sobre los elementos de una secuencia,como una lista.
En este caso, se itera sobre cada elemento de la lista "animales" y se imprime cada animal en una línea separada."""


for animal in animales:
    print(animal)
    

